    always @(posedge clk) begin
        b1 <= {b1[0], S1};
        b2 <= {b2[0], S2};
    end

    reg select_img=0, done=0;
    reg [21:0] startup=0;
    reg [6:0] div=0, col=0;
    reg [2:0] page=0, bit_no=7;
    reg [9:0] index=0;
    reg [7:0] shifter=0;
    reg [1:0] state=0;

    // Fiecare grup de 8 randuri devine un octet PCD8544.
    // bit 0 = pixelul de sus; bit 7 = pixelul de jos.
    wire [6:0] y = {1'b0, page, 3'b000} + (select_img ? 7'd48 : 7'd0);
    wire [6:0] xbit = 7'd83-col;
    wire [7:0] octet = {
        pixeli[y+7][xbit], pixeli[y+6][xbit],
        pixeli[y+5][xbit], pixeli[y+4][xbit],
        pixeli[y+3][xbit], pixeli[y+2][xbit],
        pixeli[y+1][xbit], pixeli[y+0][xbit]
    };
    wire [7:0] data_byte = (index<10'd8) ? cmd(index[2:0]) : octet;

    always @(posedge clk) begin
        if (startup < 22'd2500000) begin
            startup <= startup+1'b1;
            if (startup == 22'd1000000) lcd_rst <= 1;
        end
        else if (done) begin
            if (!b1[1] && b2[1] && select_img) begin
                select_img<=0; index<=6; col<=0; page<=0; done<=0;
            end
            else if (!b2[1] && b1[1] && !select_img) begin
                select_img<=1; index<=6; col<=0; page<=0; done<=0;
            end
        end
        else if (div == 7'd99) begin
            div<=0;
            case (state)
                0: begin
                    lcd_ce<=0; lcd_dc<=(index>=8);
                    lcd_din<=data_byte[7]; shifter<=data_byte;
                    bit_no<=7; state<=1;
                end
                1: begin lcd_clk<=1; state<=2; end
                2: begin
                    lcd_clk<=0;
                    if (bit_no==0) state<=3;
                    else begin
                        bit_no<=bit_no-1'b1;
                        lcd_din<=shifter[6];
                        shifter<={shifter[6:0],1'b0}; state<=1;
                    end
                end
                3: begin
                    lcd_ce<=1;
                    if(index==511) done<=1;
                    else begin
                        index<=index+1'b1;
                        if(index>=8) begin
                            if(col==83) begin
                                col<=0; page<=page+1'b1;
                            end
                            else col<=col+1'b1;
                        end
                    end
                    state<=0;
                end
            endcase
        end
        else div<=div+1'b1;
    end
