    function [7:0] cmd;
        input [2:0] n;
        begin
            case(n)
                0:cmd=8'h21; 1:cmd=8'hB8; 2:cmd=8'h04; 3:cmd=8'h14;
                4:cmd=8'h20; 5:cmd=8'h0C; 6:cmd=8'h80; 7:cmd=8'h40;
                default:cmd=8'h00;
            endcase
        end
    endfunction

